/** Logo + divider + "Market intelligence platform" — the website header
    lockup. The descriptor is set live in IBM Plex Mono (the face the
    kit's artwork uses) rather than drawn from paths: at header size the
    outlined descriptor would be ~5px tall and unreadable. */
export function LogoDescriptor({ height = 28, tone = "color", className, title = "Vemi, market intelligence platform" }: Common & { height?: number }) {
  const descriptorColor =
    tone === "color" ? "var(--vm-text-muted)"
    : tone === "onInk" ? "color-mix(in srgb, var(--vm-paper) 72%, transparent)"
    : tone === "reversed" ? "var(--vm-on-primary)"
    : "currentColor";
  return (
    <span
      className={`inline-flex items-center ${className ?? ""}`}
      style={{ ...TONES[tone], gap: height * 0.55 }}
      {...a11y(title)}
    >
      <Logo height={height} tone={tone} title="" />
      <span aria-hidden className="self-stretch" style={{ width: 1, background: "var(--logo-rule)" }} />
      <span
        aria-hidden
        className="font-mono text-xs font-medium uppercase tracking-[0.1em]"
        style={{ color: descriptorColor }}
      >
        Market intelligence
        <br />
        platform
      </span>
    </span>
  );
}
