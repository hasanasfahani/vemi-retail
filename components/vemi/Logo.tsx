export type LogoTone = "color" | "mono" | "reversed" | "onInk";

/* color    — Paper or White ground: Violet mark, Ink word.
   mono     — single color, follows `currentColor` (print, stamps).
   reversed — on a Violet fill: all white.
   onInk    — on an Ink panel: Violet 400 mark, Paper word. */
const TONES: Record<LogoTone, CSSProperties> = {
  color: {
    ["--logo-mark" as string]: "var(--vm-primary)",
    ["--logo-word" as string]: "var(--vm-text)",
    ["--logo-rule" as string]: "var(--vm-line)",
  },
  mono: {
    ["--logo-mark" as string]: "currentColor",
    ["--logo-word" as string]: "currentColor",
    ["--logo-rule" as string]: "currentColor",
  },
  reversed: {
    ["--logo-mark" as string]: "var(--vm-on-primary)",
    ["--logo-word" as string]: "var(--vm-on-primary)",
    ["--logo-rule" as string]: "color-mix(in srgb, var(--vm-on-primary) 40%, transparent)",
  },
  onInk: {
    ["--logo-mark" as string]: "var(--vm-primary-on-ink)",
    ["--logo-word" as string]: "var(--vm-paper)",
    ["--logo-rule" as string]: "var(--vm-ink-800)",
  },
};

function Blocks() {
  return (
    <g fill="var(--logo-mark)">
      {BLOCKS.map(([x, y, w, h], i) => (
        <rect key={i} x={x} y={y} width={w} height={h} rx={RX} />
      ))}
    </g>
  );
}

function Word() {
  return (
    <g transform={`translate(${WORD_X},0)`} fill="var(--logo-word)">
      {WORD.map((d, i) => (
        <path key={i} d={d} />
      ))}
    </g>
  );
}

const vb = (b: { x: number; y: number; w: number; h: number }) => `${b.x} ${b.y} ${b.w} ${b.h}`;

type Common = {
  tone?: LogoTone;
  className?: string;
  /* Accessible name. Pass "" when the logo sits inside a link that is
     already labelled, so it is not announced twice. */
  title?: string;
};

function a11y(title: string) {
  return title
    ? { role: "img" as const, "aria-label": title }
    : { "aria-hidden": true as const, focusable: "false" as const };
}

/** The Insight V on its own. `size` is its height in px (minimum 16). */
export function Mark({ size = 24, tone = "color", className, title = "Vemi" }: Common & { size?: number }) {
  const h = Math.max(16, size);
  return (
    <svg
      viewBox={vb(MARK_BOX)}
      height={h}
      width={(h * MARK_BOX.w) / MARK_BOX.h}
      className={className}
      style={TONES[tone]}
      {...a11y(title)}
    >
      <Blocks />
    </svg>
  );
}

/** Mark + wordmark, the default lockup. `height` in px; the lockup never
    renders narrower than the brand's 72px minimum. */
export function Logo({ height = 28, tone = "color", className, title = "Vemi" }: Common & { height?: number }) {
  const h = Math.max((72 * H_BOX.h) / H_BOX.w, height);
  return (
    <svg
      viewBox={vb(H_BOX)}
      height={h}
      width={(h * H_BOX.w) / H_BOX.h}
      className={className}
      style={TONES[tone]}
      {...a11y(title)}
    >
      <Blocks />
      <Word />
    </svg>
  );
}

